"""Compare two ``results/numbers.json`` files — the numbers quoted in the paper.

Why this exists
---------------
Every number in the paper is a LaTeX macro generated by the book and also
recorded, with its unrounded value, in ``results/numbers.json``.  After a
full rebuild on a new computer (or after a code change that should not move
any result) we want to know, number by number, whether anything changed and
by how much.  Floating-point arithmetic differs slightly between machines
(BLAS libraries, CPU instruction sets), so exact equality is too strict: we
compare with a relative and an absolute tolerance, like ``numpy.isclose``.

Usage
-----
    uv run python tools/compare_numbers.py OLD.json NEW.json [--rtol 1e-3] [--atol 1e-6]

Prints one line per number that differs (or exists in only one file) and a
one-line summary.  Exit status: 0 if everything agrees within tolerance,
1 otherwise — so the script can be used in a check or a CI job.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path


def load(path: Path) -> dict[str, dict]:
    """Read a numbers.json file: {macro name: {value, text, desc, chapter}}."""
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def close(a, b, rtol: float, atol: float) -> bool:
    """True if two values agree.

    Numbers are compared with |a - b| <= atol + rtol * |b|; anything that is
    not a number (a string such as a country name or a year range) must match
    exactly.
    """
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        if math.isnan(a) and math.isnan(b):
            return True
        return abs(a - b) <= atol + rtol * abs(b)
    return a == b


def compare(old: dict, new: dict, rtol: float, atol: float) -> list[str]:
    """Return a list of human-readable difference lines (empty if none)."""
    lines = []
    for name in sorted(old.keys() | new.keys()):
        if name not in new:
            lines.append(f"  only in OLD   {name:<32} {old[name]['text']}")
        elif name not in old:
            lines.append(f"  only in NEW   {name:<32} {new[name]['text']}")
        else:
            a, b = old[name]["value"], new[name]["value"]
            if not close(a, b, rtol, atol):
                chapter = new[name].get("chapter", "?")
                lines.append(
                    f"  differs       {name:<32} {old[name]['text']:>12} -> "
                    f"{new[name]['text']:<12} ({chapter})"
                )
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("old", type=Path, help="reference numbers.json (e.g. from git)")
    parser.add_argument("new", type=Path, help="numbers.json from the new build")
    parser.add_argument("--rtol", type=float, default=1e-3, help="relative tolerance (default 1e-3)")
    parser.add_argument("--atol", type=float, default=1e-6, help="absolute tolerance (default 1e-6)")
    args = parser.parse_args(argv)

    old, new = load(args.old), load(args.new)
    lines = compare(old, new, args.rtol, args.atol)
    for line in lines:
        print(line)
    # Count the three kinds separately: a number that is new or gone has not "moved".
    def count(prefix: str) -> int:
        return sum(line.lstrip().startswith(prefix) for line in lines)

    print(
        f"{len(old.keys() & new.keys())} numbers in both files; "
        f"{count('differs')} differ beyond rtol={args.rtol:g}, atol={args.atol:g}; "
        f"{count('only in NEW')} only in NEW; {count('only in OLD')} only in OLD."
    )
    return 1 if lines else 0


if __name__ == "__main__":
    raise SystemExit(main())
